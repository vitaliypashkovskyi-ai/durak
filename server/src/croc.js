const norm = s => String(s || '').toLowerCase().replace(/[ʼ’`']/g, "'").replace(/[^a-zа-яіїєґ0-9' ]/gi, ' ').replace(/\s+/g, ' ').trim();
// does the text name the word? whole word (for two-word answers — the whole phrase)
export function names(text, word) {
  const t = ' ' + norm(text) + ' ', w = norm(word);
  return t.includes(' ' + w + ' ');
}
// the explainer must not say the word or its root (first 4 letters of each part)
export function leaks(text, word) {
  const t = norm(text);
  return norm(word).split(' ').some(p => p.length >= 3 && t.split(' ').some(x => x.startsWith(p.slice(0, Math.min(4, p.length)))));
}
